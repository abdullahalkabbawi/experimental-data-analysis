"""Build LaTeX table bodies for the Hall effect lab report.

Reads the representative-data CSV files in reports/data and writes row bodies
(no tabular environment, no caption) into reports/tables. The report file
pulls them in with \\input so that no number is ever retyped by hand.

REPRESENTATIVE DATA. The CSV files this script reads were generated by
generate_hall.py and are not a record of measured results.
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPORTS = os.path.dirname(HERE)
DATA = os.path.join(REPORTS, "data")
TABLES = os.path.join(REPORTS, "tables")
os.makedirs(TABLES, exist_ok=True)


def read_csv(name):
    path = os.path.join(DATA, name)
    with open(path, "r", encoding="utf-8") as fh:
        lines = [ln for ln in fh if not ln.lstrip().startswith("#")]
    return list(csv.DictReader(lines))


# Comment header stamped on every generated fragment. The fragments are pulled
# into the report from inside a tabular, so every line here must be a complete
# LaTeX comment: a stray non-comment character would break the alignment.
HEADER = (
    "% REPRESENTATIVE DATA. Not a record of measured results.\n"
    "% Table body for hall_effect_2deg_lab_report.tex (Hall effect in a 2DEG,\n"
    "% Physics 3H laboratory, Abdullah Alkabbawi).\n"
    "% Generated by reports/analysis/make_hall_tables.py from the CSV files in\n"
    "% reports/data, which were themselves generated by generate_hall.py.\n"
    "% Do not edit by hand: rerun make_hall_tables.py instead.\n"
)


def write(name, rows):
    path = os.path.join(TABLES, name)
    # newline="\n" matters: a CR left after the final "\\" of a row breaks the
    # surrounding tabular when the fragment is pulled in with \input.
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER)
        fh.write("%\n".join(rows) + "%\n")
    print("wrote", path, len(rows), "rows")


# ---------------------------------------------------------------- magnet
cal = read_csv("hall_magnet_calibration.csv")
rising = [r for r in cal if r["branch"] == "rising"]
falling = sorted((r for r in cal if r["branch"] == "falling"),
                 key=lambda r: float(r["magnet_supply_V"]))
rows = []
for a, b in zip(rising, falling):
    rows.append(
        "{:.0f} & {:.4f} & {:.2f} & {:.0f} & {:.4f} & {:.2f} \\\\".format(
            float(a["magnet_supply_V"]), float(a["coil_current_A"]),
            1000.0 * float(a["B_measured_T"]),
            float(b["magnet_supply_V"]), float(b["coil_current_A"]),
            1000.0 * float(b["B_measured_T"])))
write("tab_magnet_calibration.tex", rows)

# ---------------------------------------------------------- longitudinal
vl300 = read_csv("hall_VL_300K.csv")
vl77 = read_csv("hall_VL_77K.csv")
rows = []
for a, b in zip(vl300, vl77):
    rows.append(
        "{:.3f} & {:.2f} & {:.2f} & {:.2f} & {:.2f} \\\\".format(
            float(a["bar_supply_V"]),
            float(a["I_uA"]), float(a["V_L_mV"]),
            float(b["I_uA"]), float(b["V_L_mV"])))
write("tab_VL_full.tex", rows)
write("tab_VL_extract.tex", [rows[i] for i in (0, 3, 6, 9, 12, 15, 17)])


# ------------------------------------------------------------- Hall arrays
def hall_block(name, out):
    data = read_csv(name)
    fields = sorted({float(r["B_T"]) for r in data})
    by_field = {f: [r for r in data if abs(float(r["B_T"]) - f) < 1e-9]
                for f in fields}
    n = len(by_field[fields[0]])
    rows = []
    for i in range(n):
        cells = ["{:.3f}".format(float(by_field[fields[0]][i]["bar_supply_V"]))]
        for f in fields:
            r = by_field[f][i]
            cells.append("{:.2f}".format(float(r["I_uA"])))
            cells.append("{:.3f}".format(float(r["V_H_mV"])))
        rows.append(" & ".join(cells) + " \\\\")
    write(out, rows)
    return fields


f300 = hall_block("hall_VH_300K.csv", "tab_VH300_full.tex")
f77 = hall_block("hall_VH_77K.csv", "tab_VH77_full.tex")
print("300 K fields:", f300)
print("77 K fields:", f77)

# ------------------------------------------------------------------ angle
ang = read_csv("hall_angle_300K.csv")
half = (len(ang) + 1) // 2
rows = []
for i in range(half):
    a = ang[i]
    # The voltage cell is set in maths mode so that negative values carry a
    # proper minus sign rather than the shorter text hyphen used elsewhere.
    left = "{:.0f} & {:.2f} & ${:.4f}$".format(
        float(a["angle_deg"]), float(a["I_uA"]), float(a["V_H_mV"]))
    if i + half < len(ang):
        b = ang[i + half]
        right = "{:.0f} & {:.2f} & ${:.4f}$".format(
            float(b["angle_deg"]), float(b["I_uA"]), float(b["V_H_mV"]))
    else:
        right = " & & "
    rows.append(left + " & " + right + " \\\\")
write("tab_angle.tex", rows)

# ----------------------------------------------------------- thermocouple
tc = read_csv("hall_thermocouple_77K.csv")
half = (len(tc) + 1) // 2
rows = []
for i in range(half):
    a = tc[i]
    b = tc[i + half]
    rows.append("{} & {:.2f} & {} & {:.2f} \\\\".format(
        a["reading_index"], float(a["T_K"]),
        b["reading_index"], float(b["T_K"])))
write("tab_thermocouple.tex", rows)

print("done")
